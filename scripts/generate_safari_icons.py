#!/usr/bin/env python3
"""Derive Safari artwork from the unchanged Icon Composer source layers."""

import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "Design/AppIcon"
IMAGES = ROOT / "Shared (Extension)/Resources/images"
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)
HEADER = '<!-- Generated by scripts/generate_safari_icons.py; edit Design/AppIcon sources. -->\n'


def layer(name):
    return ET.parse(APP / name).getroot()


def serialize(root):
    return HEADER + ET.tostring(root, encoding="unicode") + "\n"


def artwork():
    """Return deterministic generated SVGs, also used by the stale-asset test."""
    result = {}
    for beta in (False, True):
        for dark in (False, True):
            root = ET.Element(f"{{{NS}}}svg", {
                "width": "1024", "height": "1024", "viewBox": "0 0 1024 1024"
            })
            # A static WebExtension icon cannot use Composer's native material.
            # Reuse its vector layers; dark backgrounds are restrained navy/silver.
            background = layer("01-beta-background.svg" if beta else "01-background.svg")
            if dark:
                stops = background.findall(f".//{{{NS}}}linearGradient/{{{NS}}}stop")
                colors = ("#102A5B", "#0A2250", "#061738", "#030D24") if beta else (
                    "#24374A", "#142637", "#1C3044", "#0B1622", "#223143", "#101B29")
                for stop, color in zip(stops, colors):
                    stop.set("stop-color", color)
                # Keep the geometry but subdue the light reflections on a dark base.
                for gradient in background.findall(f".//{{{NS}}}radialGradient"):
                    for stop in gradient:
                        if stop.get("stop-opacity") != "0":
                            stop.set("stop-opacity", ".12")
            root.extend(list(background))
            if beta:
                root.extend(list(layer("02-beta-grid.svg")))
            letter = layer("03-beta-letter.svg" if beta else "02-letter.svg")
            if dark and not beta:
                for stop in letter.findall(f".//{{{NS}}}stop"):
                    stop.set("stop-color", "#E9F4FC")
            root.extend(list(letter))
            root.extend(list(layer("03-glass-slash.svg")))
            directory = IMAGES / "beta" if beta else IMAGES
            result[directory / ("icon-dark.svg" if dark else "icon.svg")] = serialize(root)

    letter_path = layer("02-letter.svg").find(f"{{{NS}}}path").get("d")
    ribbon_path = layer("03-glass-slash.svg").find(f"{{{NS}}}path").get("d")
    for variant in ("on", "off", "oni", "offi"):
        root = ET.Element(f"{{{NS}}}svg", {
            "width": "48", "height": "48", "viewBox": "128 128 768 768"
        })
        color = "#FFFFFF" if variant.endswith("i") else "#000000"
        if variant.startswith("on"):
            defs = ET.SubElement(root, "defs")
            mask = ET.SubElement(defs, "mask", {"id": "separation", "maskUnits": "userSpaceOnUse",
                                               "x": "0", "y": "0", "width": "1024", "height": "1024"})
            ET.SubElement(mask, "rect", {"width": "1024", "height": "1024", "fill": "white"})
            ET.SubElement(mask, "path", {"d": ribbon_path, "fill": "black", "stroke": "black",
                                         "stroke-width": "58", "stroke-linejoin": "round"})
            ET.SubElement(root, "path", {"d": letter_path, "fill": color, "mask": "url(#separation)"})
            ET.SubElement(root, "path", {"d": ribbon_path, "fill": color})
        else:
            ET.SubElement(root, "path", {"d": letter_path, "fill": color})
        result[ROOT / "Design/Toolbar" / f"{variant}.svg"] = serialize(root)
    return result


if __name__ == "__main__":
    for path, content in artwork().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
